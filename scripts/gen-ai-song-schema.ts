/**
 * Generate docs/schemas/ai-song.schema.json — the machine-readable contract
 * for `AISongData` (v1.0 and v1.1).
 *
 *   pnpm run gen:ai-song-schema            # rewrite the committed schema
 *   pnpm run check:ai-song-schema          # regenerate to a temp file, fail on drift
 *
 * The structure comes from `src/importers/ai-song/types.ts` via
 * ts-json-schema-generator. What TypeScript cannot say (ranges, the note-name
 * pattern, which parameters belong to which automation target, the version
 * split) is added in `refine()` below. The rules a JSON Schema cannot express —
 * lane length vs `stepCount`, `song` rows naming defined patterns, the
 * 32-pattern cap, song-wide lanes shadowing pattern lanes — stay in
 * `validateAISongData()`; `aiSongSchemaAgreement.test.ts` pins both sides.
 */

import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createGenerator } from 'ts-json-schema-generator';
import {
  VALID_PARAMETERS_BY_TARGET,
} from '../src/importers/ai-song/automationParameters';
import { AI_SONG_FORMAT_VERSIONS } from '../src/importers/ai-song/versioning';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMA_PATH = join(ROOT, 'docs/schemas/ai-song.schema.json');
const NOTE_PATTERN = '^[A-G][#b]?[0-8]$'; // isValidNote() in AISongImporter.ts

type Json = Record<string, any>;

function generate(): string {
  const raw = createGenerator({
    path: join(ROOT, 'src/importers/ai-song/types.ts'),
    tsconfig: join(ROOT, 'tsconfig.app.json'),
    type: 'AISongData',
    skipTypeCheck: true,
    additionalProperties: false,
    expose: 'export',
    topRef: true,
    jsDoc: 'extended',
  }).createSchema('AISongData') as Json;

  // Draft 2020-12 spells `definitions` as `$defs`.
  const defs = JSON.parse(
    JSON.stringify(raw.definitions).replaceAll('#/definitions/', '#/$defs/'),
  ) as Json;
  normalizeDeprecated(defs);
  refine(defs);

  const schema: Json = {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: 'https://hyphon.local/schemas/ai-song.schema.json',
    title: 'Hyphon AI song (AISongData v1.0 / v1.1)',
    description:
      'Generated by scripts/gen-ai-song-schema.ts from src/importers/ai-song/types.ts. ' +
      'Do not edit by hand; see docs/ai-song-format.md and docs/ai-song-agent-brief.md.',
    oneOf: [{ $ref: '#/$defs/AISongDataV1_0' }, { $ref: '#/$defs/AISongDataV1_1' }],
    $defs: defs,
  };
  return `${JSON.stringify(schema, null, 2)}\n`;
}

/** JSDoc `@deprecated why` becomes a string; 2020-12 wants `deprecated: true`. */
function normalizeDeprecated(node: unknown): void {
  if (Array.isArray(node)) return node.forEach(normalizeDeprecated);
  if (!node || typeof node !== 'object') return;
  const obj = node as Json;
  if (typeof obj.deprecated === 'string') {
    obj.description = [obj.description, `Deprecated: ${obj.deprecated}`].filter(Boolean).join(' ');
    obj.deprecated = true;
  }
  Object.values(obj).forEach(normalizeDeprecated);
}

/** The constraints the types cannot express. Mirrors `validateAISongData()`. */
function refine(defs: Json): void {
  const root = defs.AISongData as Json;
  const { meta, globals } = root.properties as Json;

  // meta — validateAISongData(): title ≤ 100, author / generator / prompt non-blank.
  meta.properties.title.minLength = 1;
  meta.properties.title.maxLength = 100;
  for (const field of ['author', 'generator', 'prompt']) {
    meta.properties[field].pattern = '\\S';
  }
  meta.properties.version = { enum: [...AI_SONG_FORMAT_VERSIONS] };

  // globals
  Object.assign(globals.properties.tempo, { minimum: 30, maximum: 300 });
  Object.assign(globals.properties.swing, { minimum: 0, maximum: 100 });
  Object.assign(globals.properties.stepCount, { type: 'integer', minimum: 1, maximum: 64 });
  Object.assign(globals.properties.timeSignature.items, { type: 'integer', minimum: 1, maximum: 32 });

  // v1.1 song block
  root.properties.patterns.minProperties = 1;
  root.properties.patterns.propertyNames = { pattern: '\\S' };
  root.properties.song.minItems = 1;

  // notes
  const note = defs.AINoteEvent.properties as Json;
  Object.assign(note.step, { type: 'integer', minimum: 0, maximum: 63 });
  note.note.pattern = NOTE_PATTERN;
  Object.assign(note.velocity, { minimum: 0, maximum: 1 });
  Object.assign(note.length, { minimum: 1 });

  // sampler banks
  Object.assign(defs.AISamplerBankData.properties.bankIndex, { type: 'integer', minimum: 0, maximum: 7 });
  defs.AISongTracks.properties.sampler.maxItems = 8;

  // automation lanes — 0..127 or null, and `parameter` must belong to `target`.
  const lane = defs.AIAutomationLane as Json;
  Object.assign(lane.properties.steps, {
    minItems: 1,
    items: { oneOf: [{ type: 'integer', minimum: 0, maximum: 127 }, { type: 'null' }] },
  });
  lane.allOf = Object.entries(VALID_PARAMETERS_BY_TARGET).map(([target, parameters]) => ({
    if: { properties: { target: { const: target } }, required: ['target'] },
    then: { properties: { parameter: { enum: [...parameters] } } },
  }));

  // `required` only inside a schema that also lists the names (ajv strictRequired).
  const has = (...names: string[]): Json => ({
    properties: Object.fromEntries(names.map((n) => [n, true])),
    required: names,
  });

  // Version split: v1.0 is one pattern; v1.1 is `tracks` xor `patterns` + `song`.
  const version = (v: string): Json => ({
    type: 'object',
    properties: { meta: { type: 'object', properties: { version: { const: v } }, required: ['version'] } },
  });
  defs.AISongDataV1_0 = {
    type: 'object',
    allOf: [{ $ref: '#/$defs/AISongData' }, version('1.0')],
    required: ['tracks'],
    properties: { tracks: true, globals: { type: 'object', not: has('stepCount') } },
    not: { anyOf: [has('patterns'), has('song')] },
  };
  defs.AISongDataV1_1 = {
    type: 'object',
    allOf: [{ $ref: '#/$defs/AISongData' }, version('1.1')],
    oneOf: [
      { ...has('tracks'), not: has('patterns') },
      { ...has('patterns', 'song'), not: has('tracks') },
    ],
  };
}

const check = process.argv.includes('--check');
const next = generate();

if (!check) {
  writeFileSync(SCHEMA_PATH, next);
  console.log(`wrote ${SCHEMA_PATH}`);
} else {
  const dir = mkdtempSync(join(tmpdir(), 'ai-song-schema-'));
  try {
    const tmp = join(dir, 'ai-song.schema.json');
    writeFileSync(tmp, next);
    let committed = '';
    try {
      committed = readFileSync(SCHEMA_PATH, 'utf8');
    } catch {
      // missing file is drift too
    }
    if (readFileSync(tmp, 'utf8') !== committed) {
      console.error(
        'docs/schemas/ai-song.schema.json is out of date with src/importers/ai-song/types.ts.\n' +
          'Run `pnpm run gen:ai-song-schema` and commit the result.',
      );
      process.exitCode = 1;
    } else {
      console.log('ai-song.schema.json is up to date');
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}
