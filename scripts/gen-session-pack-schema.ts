/**
 * Generate the session-pack contract from `src/session/pack/schema.ts`:
 *
 *   docs/schemas/session-pack.schema.json          the public JSON Schema (2020-12)
 *   src/session/pack/generated/packValidator.js    the validator the importer runs
 *
 *   pnpm run gen:session-pack-schema     # rewrite both
 *   pnpm run check:session-pack-schema   # regenerate in memory, fail on drift
 *
 * The validator is ajv's standalone code generation, like the co-producer's:
 * the app ships these functions, not ajv, and nothing in them evaluates code.
 * `unicode: false` counts string length in UTF-16 units (JS `.length`, which is
 * also what the size limits in docs/session-pack-format.md mean); formats are
 * not used by the schema.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020';
import standaloneCode from 'ajv/dist/standalone';
import { buildSessionPackSchema } from '../src/session/pack/schema';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMA_PATH = join(ROOT, 'docs/schemas/session-pack.schema.json');
const VALIDATOR_PATH = join(ROOT, 'src/session/pack/generated/packValidator.js');

const BANNER = [
  '// Generated by scripts/gen-session-pack-schema.ts from src/session/pack/schema.ts.',
  '// Do not edit; run `pnpm run gen:session-pack-schema`.',
  '/* eslint-disable */',
].join('\n');

type Json = Record<string, unknown>;

/** Descriptions are for people reading the schema, not for validation: leave them out of the shipped code. */
function stripAnnotations(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(stripAnnotations);
  if (!node || typeof node !== 'object') return node;
  const out: Json = {};
  for (const [key, value] of Object.entries(node as Json)) {
    if (key === 'description' || key === 'title' || key === '$id') continue;
    out[key] =
      key === 'properties' || key === '$defs'
        ? Object.fromEntries(Object.entries(value as Json).map(([k, v]) => [k, stripAnnotations(v)]))
        : stripAnnotations(value);
  }
  return out;
}

function generate(): { schema: string; validator: string } {
  const schema = buildSessionPackSchema();
  const ajv = new Ajv2020({
    code: { source: true, esm: true, lines: false, optimize: true },
    strict: true,
    allowUnionTypes: true,
    // One function per $def, called by reference: inlining would copy the ~100-field Step check into every pattern.
    inlineRefs: false,
    allErrors: false,
    // The importer words its own errors from keyword + params; ajv's default message strings would only add bytes.
    messages: false,
    validateFormats: false,
    unicode: false,
    // `unicode` is deprecated in ajv 8; it is the setting we want (see above).
    logger: {
      log: () => {},
      warn: (...args: unknown[]) => {
        if (!/option unicode/.test(String(args[0]))) console.warn(...args);
      },
      error: (...args: unknown[]) => console.error(...args),
    },
  } as ConstructorParameters<typeof Ajv2020>[0]);
  ajv.addSchema(stripAnnotations(schema) as Json, 'session_pack');
  const code = standaloneCode(ajv, { validate_session_pack: 'session_pack' });
  if (/\brequire\(|^\s*import\s/m.test(code)) {
    throw new Error('standalone validator would import a runtime helper; keep the schema to keywords that need none');
  }
  return {
    schema: `${JSON.stringify(schema, null, 2)}\n`,
    validator: `${BANNER}\n${code}\n`,
  };
}

function read(path: string): string {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return ''; // a missing file is drift too
  }
}

const check = process.argv.includes('--check');
const next = generate();

if (!check) {
  writeFileSync(SCHEMA_PATH, next.schema);
  writeFileSync(VALIDATOR_PATH, next.validator);
  console.log(`wrote ${SCHEMA_PATH} and ${VALIDATOR_PATH} (${next.validator.length} bytes)`);
} else {
  const stale = [
    next.schema !== read(SCHEMA_PATH) ? 'docs/schemas/session-pack.schema.json' : null,
    next.validator !== read(VALIDATOR_PATH) ? 'src/session/pack/generated/packValidator.js' : null,
  ].filter(Boolean);
  if (stale.length > 0) {
    console.error(
      `${stale.join(' and ')} out of date with src/session/pack/schema.ts.\n` +
        'Run `pnpm run gen:session-pack-schema` and commit the result.',
    );
    process.exitCode = 1;
  } else {
    console.log('session-pack schema and validator are up to date');
  }
}
