/**
 * Generate src/agent/coproducer/generated/toolValidators.js — the co-producer
 * tools' input validators, precompiled by ajv's standalone code generation.
 *
 *   pnpm run gen:coproducer-validators     # rewrite the committed validators
 *   pnpm run check:coproducer-validators   # regenerate in memory, fail on drift
 *
 * Tool inputs stream in eagerly (`eager_input_streaming`), so the API does not
 * validate them and every tool's `run` must. The validators come from
 * `TOOL_INPUT_SCHEMAS` (src/agent/coproducer/toolSchemas.ts), whose
 * `import_song` entry is docs/schemas/ai-song.schema.json — so this file is
 * stale whenever either changes, and `pnpm lint` says so.
 *
 * The output imports nothing: the app ships these functions, not ajv.
 * `unicode: false` counts string length in UTF-16 units — the importer's own
 * `title.length > 100` rule — and keeps ajv's ucs2length helper out. Formats
 * are not checked (the importer does not read `createdAt` either).
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020';
import standaloneCode from 'ajv/dist/standalone';
import { TOOL_INPUT_SCHEMAS } from '../src/agent/coproducer/toolSchemas';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_PATH = join(ROOT, 'src/agent/coproducer/generated/toolValidators.js');

const BANNER = [
    '// Generated by scripts/gen-coproducer-validators.ts from src/agent/coproducer/toolSchemas.ts',
    '// and docs/schemas/ai-song.schema.json. Do not edit; run `pnpm run gen:coproducer-validators`.',
    '/* eslint-disable */',
].join('\n');

type Json = Record<string, unknown>;

/** Descriptions are for the model, not for validation: leave them out of the shipped code. */
function stripAnnotations(node: unknown): unknown {
    if (Array.isArray(node)) return node.map(stripAnnotations);
    if (!node || typeof node !== 'object') return node;
    const out: Json = {};
    for (const [key, value] of Object.entries(node as Json)) {
        if (key === 'description' || key === 'deprecated' || key === 'title') continue;
        out[key] = key === 'properties' || key === '$defs'
            ? Object.fromEntries(Object.entries(value as Json).map(([k, v]) => [k, stripAnnotations(v)]))
            : stripAnnotations(value);
    }
    return out;
}

function generate(): string {
    const ajv = new Ajv2020({
        code: { source: true, esm: true, lines: false, optimize: true },
        strict: true,
        allErrors: false,
        validateFormats: false,
        unicode: false,
        // `unicode` is deprecated in ajv 8; it is the setting we want (see above).
        logger: {
            log: () => {},
            warn: (...args: unknown[]) => {
                if (!/option unicode/.test(String(args[0]))) console.warn(...args);
            },
            error: (...args: unknown[]) => console.error(...args),
        },
    } as ConstructorParameters<typeof Ajv2020>[0]);
    const refs: Record<string, string> = {};
    for (const [name, schema] of Object.entries(TOOL_INPUT_SCHEMAS)) {
        ajv.addSchema(stripAnnotations(schema) as Json, name);
        // `export` is a reserved word: every validator is exported as `validate_<tool>`.
        refs[`validate_${name}`] = name;
    }
    const code = standaloneCode(ajv, refs);
    if (/\brequire\(|^\s*import\s/m.test(code)) {
        throw new Error('standalone validators would import a runtime helper; keep the schemas to keywords that need none');
    }
    return `${BANNER}\n${code}\n`;
}

const check = process.argv.includes('--check');
const next = generate();

if (!check) {
    writeFileSync(OUT_PATH, next);
    console.log(`wrote ${OUT_PATH} (${next.length} bytes)`);
} else {
    let committed = '';
    try {
        committed = readFileSync(OUT_PATH, 'utf8');
    } catch {
        // missing file is drift too
    }
    if (next !== committed) {
        console.error(
            'src/agent/coproducer/generated/toolValidators.js is out of date with the co-producer tool schemas.\n' +
                'Run `pnpm run gen:coproducer-validators` and commit the result.',
        );
        process.exitCode = 1;
    } else {
        console.log('coproducer toolValidators.js is up to date');
    }
}
