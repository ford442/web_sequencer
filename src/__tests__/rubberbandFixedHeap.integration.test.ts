/** A sung-ish phrase: a gliding harmonic tone with a little xorshift noise. */
function phrase(seconds: number): Float32Array {
  const out = new Float32Array(Math.round(seconds * SR));
  let x = 0x9e3779b9;
  for (let i = 0; i < out.length; i++) {
    x ^= x << 13; x ^= x >>> 17; x ^= x << 5; x >>>= 0;
    const t = i / SR;
    const f0 = 200 + 30 * Math.sin(2 * Math.PI * 1.3 * t);
    out[i] = 0.3 * (Math.sin(2 * Math.PI * f0 * t) + 0.4 * Math.sin(4 * Math.PI * f0 * t))
      + 0.01 * (x / 4294967296 - 0.5);
  }
  return out;
}

const rms = (x: Float32Array) => {
  let e = 0;
  for (const v of x) e += v * v;
  return Math.sqrt(e / Math.max(1, x.length));
};

/**
 * The fixture scenario: one mono real-time stretcher per profile, pitch and time
 * ratio moving every block, fed from `phrase(3)` on demand, 128 frames retrieved
 * per block. Returns the hash of every retrieved float32 sample.
 */
function renderStretcherGolden(
  module: Parameters<typeof assertRubberBandStretcherModule>[0],
  options: number,
  { sampleRate, quantum, blocks, inputSeconds }: Golden['scenario'],
): { frames: number; rms: number; sha256: string } {
  assertRubberBandStretcherModule(module);
  const src = phrase(inputSeconds);
  const s = new RubberBandStretcher(module, sampleRate, 1, options, 1, 1);
  const io = module._malloc(16384 * 4);
  const out = new Float32Array(blocks * quantum);
  let cursor = 0;
  let written = 0;
  for (let b = 0; b < blocks; b++) {
    s.setPitchScale(1 + 0.25 * Math.sin(b / 30));
    s.setTimeRatio(1 + 0.3 * Math.sin(b / 47));
    const need = Math.min(s.getSamplesRequired(), 16384, src.length - cursor);
    if (need > 0) {
      module.HEAPF32.set(src.subarray(cursor, cursor + need), io >> 2);
      cursor += need;
      s.process(io, need, false);
    }
    const got = s.retrieve(io, Math.min(Math.max(0, s.available()), quantum));
    out.set(module.HEAPF32.subarray(io >> 2, (io >> 2) + got), written);
    written += got;
  }
  s.delete();
  module._free(io);
  const used = out.subarray(0, written);
  return {
    frames: written,
    rms: Number(rms(used).toFixed(6)),
    sha256: createHash('sha256').update(new Uint8Array(used.buffer, 0, written * 4)).digest('hex'),
  };
}

function params(overrides: Record<string, number>): Record<string, Float32Array> {
  return Object.fromEntries(RUBBERBAND_PARAMETER_DESCRIPTORS.map((d) => [
    d.name,
    new Float32Array([overrides[d.name] ?? d.defaultValue]),
  ]));
}

const INIT_WASM = () => ({
  type: 'INIT_WASM',
  inputBuffer: new SharedArrayBuffer(4096 * 4),
  outputBuffer: new SharedArrayBuffer(4096 * 4),
  wasmBinary: readFileSync(join(ROOT, 'public/rubberband.wasm')),
});

function resetSession(): void {
  let seed = 12345;
  Math.random = () => {
    seed = (seed * 1103515245 + 12345) % 2147483648;
    return seed / 2147483648;
  };
  clock.currentTime = 0;
  posted.length = 0;
}

const fxBackendMessages = () =>
  posted.filter((m) => (m as { type?: string }).type === 'FX_BACKEND') as Array<{ backend: string; reason?: string }>;

/** RubberBandProcessor: boot, load, noteOn, stream / freeze / stream with the FX chain on. */
async function vocalSession(sample: Float32Array, profile?: string) {
  resetSession();
  const processor = new (processors.get('RubberBandProcessor')!)();
  await processor.handleMessage({ data: INIT_WASM() });
  const module = loadedModules[loadedModules.length - 1];
  await processor.handleMessage({ data: { type: 'loadBuffer', data: { buffer: sample.buffer } } });
  await processor.handleMessage({
    data: { type: 'setCustomWindowShape', data: { shape: Array.from({ length: 512 }, (_, i) => Math.sin((Math.PI * i) / 511)) } },
  });
  if (profile) await processor.handleMessage({ data: { type: 'setStretchProfile', data: { profile } } });
  await processor.handleMessage({ data: { type: 'noteOn', data: { pitch: 1.2, velocity: 0.9 } } });

  const fxOn = { timeRatio: 1.3, vocalChorus: 0.5, spectralComp: 0.4, subHarmonics: 0.3, grainJitter: 0.3, vibratoDepth: 0.2 };
  const streaming = params(fxOn);
  const frozen = params({ ...fxOn, freeze: 1 });
  const out = new Float32Array(BLOCKS * QUANTUM);
  for (let b = 0; b < BLOCKS; b++) {
    const l = new Float32Array(QUANTUM);
    const r = new Float32Array(QUANTUM);
    processor.process([], [[l, r]], b >= FREEZE_BLOCKS[0] && b < FREEZE_BLOCKS[1] ? frozen : streaming);
    out.set(l, b * QUANTUM);
    clock.currentTime += QUANTUM / SR;
  }
  return { out, module, ready: posted.find((m) => (m as { type?: string }).type === 'READY') as { fxBackend?: string } };
}

describe('rubberband.wasm module contract', () => {
  it('has a fixed memory of the budget size, no embind and no exception runtime', () => {
    requireRepoArtifacts(ARTIFACTS);
    const wasm = readFileSync(join(ROOT, 'public/rubberband.wasm'));
    const glue = readFileSync(join(ROOT, 'src/audio-worklets/rubberband-lib.js'), 'utf8');
    const required = RB_REQUIRED_EXPORTS.map((name) => name.slice(1));
    expect(checkRubberBandModule(wasm, glue, budget.rubberband.initialMemoryMb, required)).toEqual([]);
  });
});

describe('rb_* stretcher vs the embind build (golden)', () => {
  const golden = JSON.parse(readFileSync(join(ROOT, 'src/test/fixtures/rubberbandStretcherGolden.json'), 'utf8')) as Golden;

  it.each(Object.keys(golden.profiles))('%s profile renders bit-identically', async (name) => {
    const module = await createRubberBandModule({ wasmBinary: readFileSync(join(ROOT, 'public/rubberband.wasm')) });
    const expected = golden.profiles[name];
    const got = renderStretcherGolden(module, expected.options, golden.scenario);
    expect(got.frames).toBe(expected.frames);
    expect(got.rms).toBe(expected.rms);
    expect(got.sha256).toBe(expected.sha256);
    expect(module.HEAPF32.buffer.byteLength).toBe(HEAP_BYTES);
  });
});

describe('the live worklets on the fixed heap', () => {
  it('RubberBandProcessor sings on the native FX chain without the heap changing size', async () => {
    const { out, module, ready } = await vocalSession(phrase(2));
    expect(ready?.fxBackend).toBe('native');
    expect(fxBackendMessages()).toEqual([]);
    expect(rms(out)).toBeGreaterThan(0.01);
    expect(module.HEAPF32.buffer.byteLength).toBe(HEAP_BYTES);
  });

  it('setStretchProfile replaces the stretcher (threw on the embind build)', async () => {
    const errors = vi.spyOn(console, 'error').mockImplementation(() => {});
    const { out, module } = await vocalSession(phrase(2), 'harmonic');
    expect(errors).not.toHaveBeenCalled();
    errors.mockRestore();
    expect(rms(out)).toBeGreaterThan(0.01);
    expect(module.HEAPF32.buffer.byteLength).toBe(HEAP_BYTES);
  });

  it('sustain-processor stretches a slice on it', async () => {
    resetSession();
    const errors = vi.spyOn(console, 'error').mockImplementation(() => {});
    const processor = new (processors.get('sustain-processor')!)() as Processor & {
      port: { onmessage: (e: { data: Record<string, unknown> }) => Promise<void> };
    };
    const send = (data: Record<string, unknown>) => processor.port.onmessage({ data });
    await send(INIT_WASM());
    const module = loadedModules[loadedModules.length - 1];
    await send({ type: 'loadBuffer', data: { buffer: phrase(2).buffer } });
    await send({ type: 'enableRubberBand', data: { enabled: true } });
    await send({ type: 'noteOn', data: { pitch: 1.5 } });
    const parameters = {
      mode: new Float32Array([3]),
      bpm: new Float32Array([120]),
      arp: new Float32Array([0]),
      pitch: new Float32Array([1.5]),
      frequency: new Float32Array([220]),
    };
    const out = new Float32Array(BLOCKS * QUANTUM);
    for (let b = 0; b < BLOCKS; b++) {
      const l = new Float32Array(QUANTUM);
      processor.process([], [[l, new Float32Array(QUANTUM)]], parameters);
      out.set(l, b * QUANTUM);
    }
    // Rubber Band's own overrun warnings (the whole slice is fed at noteOn) are
    // expected; a broken stretcher would surface as the processor's DSP error.
    expect(errors).not.toHaveBeenCalledWith('Rubber Band DSP Error:', expect.anything());
    errors.mockRestore();
    expect(rms(out)).toBeGreaterThan(0.01);
    expect(module.HEAPF32.buffer.byteLength).toBe(HEAP_BYTES);
  });

  it('a sample longer than the fixed heap falls back to the TS FX chain and keeps singing', async () => {
    // A tone of more floats than the whole heap: rb_fx_sample_alloc cannot hold it.
    const frames = HEAP_BYTES / 4 + SR;
    const long = new Float32Array(frames);
    long.set(phrase(2));
    const errors = vi.spyOn(console, 'error').mockImplementation(() => {});
    const { out, module } = await vocalSession(long);
    errors.mockRestore();
    const fallbacks = fxBackendMessages();
    expect(fallbacks).toHaveLength(1);
    expect(fallbacks[0]).toMatchObject({ backend: 'ts', reason: expect.stringContaining('rb_fx_sample_alloc') });
    expect(rms(out)).toBeGreaterThan(0.01);
    expect(module.HEAPF32.buffer.byteLength).toBe(HEAP_BYTES);
  });
});
