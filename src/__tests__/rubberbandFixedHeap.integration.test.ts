/**
 * public/rubberband.wasm on the plain C ABI with a FIXED heap (#1596 follow-up P2,
 * docs/wasm/BUILD_NOTES.md#rubberband-fixed-memory).
 *
 *   1. The built module is real-time safe: fixed memory of the budget's size, no
 *      embind, no C++ exception runtime (tools/check_rubberband_module.mjs).
 *   2. The rb_* stretcher renders bit-identically to the embind build it replaced,
 *      on every stretch profile (src/test/fixtures/rubberbandStretcherGolden.json).
 *   3. The live worklets — RubberBandProcessor (live vocal; the offline vocal host
 *      runs the same class) and sustain-processor — sing on it, the heap never
 *      changes size, and setStretchProfile works (it threw on the embind build:
 *      getTimeRatio / getPitchScale were never bound).
 *   4. A sample too long for the fixed heap does not abort the module or grow it:
 *      rb_fx_sample_alloc fails, the worklet reports the TS FX fallback, and the
 *      voice keeps singing.
 *
 * This replaced rubberbandHeapGrowth.integration.test.ts: with growth gone there is
 * no grow left to inject.
 */

