const SR = 48000;
const QUANTUM = 128;
const BLOCKS = 240;
const FREEZE_BLOCKS = [120, 180] as const;
const ARTIFACTS = ['public/rubberband.wasm', 'src/audio-worklets/rubberband-lib.js'] as const;

type Processor = {
  handleMessage(event: { data: Record<string, unknown> }): Promise<void>;
  process(inputs: unknown, outputs: Float32Array[][], parameters: Record<string, Float32Array>): boolean;
};
type Golden = {
  scenario: { sampleRate: number; quantum: number; blocks: number; inputSeconds: number };
  profiles: Record<string, { options: number; frames: number; rms: number; sha256: string }>;
};

