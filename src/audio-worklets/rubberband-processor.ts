import { ExpressiveVoiceProcessor } from "../engines/rubberband/ExpressiveVoiceProcessor";
import { WorkletPerfReporter } from "./workletPerfReporter";
import { resolveWorkletSampleRate } from "../utils/workletSampleRate";
import { RUBBERBAND_PARAMETER_DESCRIPTORS } from "./rubberband/parameterDescriptors";
import { getPhonemeDataAtSample, type PhonemeSample } from "./rubberband/phonemeData";
import { GranularEngine } from "./rubberband/granularEngine";
import { SpectralBandProcessor } from "./rubberband/spectralEffects";
import { VocalChorusEffect } from "./rubberband/chorusEffect";
import { SubHarmonicsEffect } from "./rubberband/subHarmonics";
import { Bitcrusher } from "./rubberband/bitcrusher";
import { PhonemeToneFilter, SyllableVolumeFilter, TranceGate } from "./rubberband/toneFilters";
import { DrumDuckEnvelope } from "./rubberband/drumDuckEnvelope";
// @ts-ignore - The file is generated by the build script
import createRubberBandModule from "./rubberband-lib.js";


interface AudioWorkletProcessor {
  readonly port: MessagePort;
  process(inputs: Float32Array[][], outputs: Float32Array[][], parameters: Record<string, Float32Array>): boolean;
}

declare var AudioWorkletProcessor: {
  prototype: AudioWorkletProcessor;
  new(options?: any): AudioWorkletProcessor;
};

declare function registerProcessor(name: string, processorCtor: (new (options?: any) => AudioWorkletProcessor)): void;

declare const globalThis: {
  sampleRate: number;
};

class RubberBandProcessor extends AudioWorkletProcessor {
  private rubberBand: any = null;
  private inputRingBuffer: RingBuffer | null = null;
  private outputRingBuffer: RingBuffer | null = null;
  private expressiveProcessor: ExpressiveVoiceProcessor;
  private readonly perf = new WorkletPerfReporter(this.port, 'rubberband');

  // DSP effect modules (each owns its own state)
  private readonly granular = new GranularEngine();
  private readonly spectral = new SpectralBandProcessor();
  private readonly chorus = new VocalChorusEffect();
  private readonly subHarmonics = new SubHarmonicsEffect();
  private readonly bitcrusher = new Bitcrusher();
  private readonly phonemeToneFilter = new PhonemeToneFilter();
  private readonly syllableVolumeFilter = new SyllableVolumeFilter();
  private readonly tranceGate = new TranceGate();
  private readonly drumDuck = new DrumDuckEnvelope();

  // WASM Memory Management
  private inputHeapPtr: number = 0;
  private outputHeapPtr: number = 0;
  private heapSizeFrames: number = 0;

  // Audio State
  private sampleRate = 44100;
  private initialized = false;
  private fullSampleBuffer: Float32Array | null = null;

  // Phoneme Data
  private phonemeData: Float32Array | null = null;
  private phonemeRatios: number[] | null = null;

  // Drum Envelope Sidechain
  private drumSidechainSAB: Float32Array | null = null;

  // Playback State (Unified)
  private isPlaying = false;
  private isReverse = false;

  private currentSamplePtr = 0;
  private startSamplePtr = 0;
  private endSamplePtr = 0;
  private basePitch = 1.0;
  private targetHz: number = 0;
  static get parameterDescriptors() {
    return RUBBERBAND_PARAMETER_DESCRIPTORS;
  }

  // Pitch Correction State
  private pitchDetectState = {
    lastSample: 0,
    lastCrossIndex: 0,
    periods: new Float32Array(5),
    periodIndex: 0,
    lastValidF0: 0,
    smoothCorr: 1.0
  };

  // Auto-Tune State
  private autoTuneLastSign: number = 0;
  private autoTuneSamplesSinceZero: number = 0;
  private autoTuneSmoothedPeriod: number = 0;

  constructor() {
    super();
    this.port.onmessage = this.handleMessage.bind(this);
    // @ts-ignore
    this.sampleRate = resolveWorkletSampleRate();

    this.expressiveProcessor = new ExpressiveVoiceProcessor({
      sampleRate: this.sampleRate
    });
  }

  async handleMessage(event: MessageEvent) {
    const { type, data } = event.data;

    switch (type) {
      case 'INIT_WASM':
        try {
          const { inputBuffer, outputBuffer, wasmBinary, baseUrl, drumSidechainSAB } = event.data;

          this.inputRingBuffer = new RingBuffer(inputBuffer);
          this.outputRingBuffer = new RingBuffer(outputBuffer);

          if (drumSidechainSAB) {
            this.drumSidechainSAB = new Float32Array(drumSidechainSAB);
          }

          if (!wasmBinary) {
            throw new Error("WASM binary not provided in INIT_WASM message");
          }

          const wasmPath = `${baseUrl || '/'}rubberband.wasm`;
          // Instantiate WASM module with the provided binary
          // @ts-ignore
          const module = await createRubberBandModule({
            wasmBinary: wasmBinary,
            locateFile: (path: string) => {
              if (path.endsWith('.wasm')) return wasmPath;
              return path;
            }
          });

          const safeSampleRate = Math.floor(resolveWorkletSampleRate({ sampleRate: this.sampleRate }));

          // Options: RealTime (1) | Finer (32) | FormantPreserved (1048576) = 1048609
          const options = 1 | 32 | 1048576;

          console.log(`[RubberBandProcessor] Initializing with: Rate=${safeSampleRate}, Ch=1, Opts=${options}`);

          this.rubberBand = new module.RubberBandStretcher(
            safeSampleRate,
            1, // Mono
            options,
            1.0, // Initial Time Ratio
            1.0  // Initial Pitch Scale
          );

          this.rubberBand.module = module;
          this.initialized = true;
          this.port.postMessage({ type: 'READY' });
        } catch (e) {
          console.error("RubberBand WASM Failed:", e);
          this.port.postMessage({ type: 'ERROR', error: String(e) });
        }
        break;

      case 'loadBuffer':
        if (data && data.buffer) {
          this.fullSampleBuffer = new Float32Array(data.buffer);
        }
        break;

      case 'setCustomWindowShape':
        if (data.shape && data.shape.length > 0) {
          this.granular.setCustomWindowShape(new Float32Array(data.shape));
        } else {
          this.granular.setCustomWindowShape(null);
        }
        break;

      case 'setPhonemeData':
        if (data && data.sharedBuffer) {
          this.phonemeData = new Float32Array(data.sharedBuffer);
          this.phonemeRatios = data.ratios || null;
        }
        break;
      case 'noteOn':
        if (!this.initialized || !this.fullSampleBuffer || !data) return;
        this.rubberBand.reset();

        // Store base pitch for combination with parameters
        this.basePitch = data.pitch || 1.0;
        if (data.targetHz) {
           this.targetHz = data.targetHz;
        }
        this.rubberBand.setPitchScale(this.basePitch);
        this.rubberBand.setTimeRatio(1.0);
        this.expressiveProcessor.reset();
        this.expressiveProcessor.noteOn();

        const startSample = Math.max(0, Math.floor(data.startSample || 0));
        const endSample = data.endSample
          ? Math.min(this.fullSampleBuffer.length, Math.floor(data.endSample))
          : this.fullSampleBuffer.length;

        if (startSample >= endSample) return;

        this.isReverse = !!data.reverse;

        // Initialize streaming state
        this.startSamplePtr = startSample;
        this.endSamplePtr = endSample;

        if (this.isReverse) {
          this.currentSamplePtr = endSample - 1;
        } else {
          this.currentSamplePtr = startSample;
        }

        this.isPlaying = true;
        this.syllableVolumeFilter.resetHoldState();
        break;

      case 'noteOff':
        const targetTime = data?.time;
        this.expressiveProcessor.noteOff(targetTime);
        break;

      case 'setStretchProfile':
        // Update RubberBand quality options (requires reset)
        if (data && typeof data.profile === 'string') {
          if (this.rubberBand) {
             const timeRatio = this.rubberBand.getTimeRatio();
             const pitchScale = this.rubberBand.getPitchScale();

             let options = 1 | 32 | 1048576; // Default to vocal

             if (data.profile === 'harmonic') {
                 options = 1 | 32 | 256 | 0x02000000; // OptionProcessRealTime | OptionEngineFiner | OptionTransientsMixed | OptionPitchHighQuality
             } else if (data.profile === 'fast') {
                 options = 1; // OptionProcessRealTime | OptionEngineFaster
             } else {
                 options = 1 | 32 | 256 | 1048576; // OptionProcessRealTime | OptionEngineFiner | OptionTransientsMixed | OptionFormantPreserved
             }

             // Free old buffers if they exist
             if (this.inputHeapPtr) this.rubberBand.module._free(this.inputHeapPtr);
             if (this.outputHeapPtr) this.rubberBand.module._free(this.outputHeapPtr);
             this.inputHeapPtr = 0;
             this.outputHeapPtr = 0;
             this.heapSizeFrames = 0;

             // Recreate Stretcher
             this.rubberBand = new this.rubberBand.module.RubberBandStretcher(
               this.sampleRate,
               1, // Mono
               options,
               1.0, // Initial Time Ratio
               1.0  // Initial Pitch Scale
             );



             this.rubberBand.setTimeRatio(timeRatio);
             this.rubberBand.setPitchScale(pitchScale);
          }
        }
        break;

      case 'setAutoFollow':
        // Enable/disable auto pitch following from sequencer
        if (data && typeof data.enabled === 'boolean') {
          // this.autoFollowEnabled = data.enabled;
        }
        break;

      case 'setCustomGrainEnvelope':
        if (data && Array.isArray(data.shape)) {
          this.granular.setCustomGrainEnvelope(data.shape);
        } else {
          this.granular.setCustomGrainEnvelope(null);
        }
        break;
    }
  }

  private getPhonemeDataAtSample(currentSample: number): PhonemeSample {
    return getPhonemeDataAtSample(this.phonemeData, this.phonemeRatios, currentSample);
  }

  process(_inputs: Float32Array[][], outputs: Float32Array[][], parameters: Record<string, Float32Array>): boolean {
    const outputChannel = outputs[0][0];
    const blockFrames = outputChannel?.length ?? 128;
    this.perf.beginProcess(blockFrames);
    try {
    outputChannel.fill(0);

    if (!this.initialized || !this.rubberBand || !this.outputRingBuffer) {
      return true;
    }

    // We need to pass the block's start time to ExpressiveVoiceProcessor for accurate timing.
    // In AudioWorklets, the current time is `globalThis.currentTime`.
    // @ts-ignore
    const currentTime = typeof globalThis.currentTime === 'number' ? globalThis.currentTime : 0;
    this.expressiveProcessor.setCurrentTime(currentTime);

    const envelopeValue = this.expressiveProcessor.getCurrentEnvelopeValue();

    const pitchEnvelopeValue = this.expressiveProcessor.getCurrentPitchEnvelopeValue();


    const pitch = parameters.pitchScale[0];
    const defaultTimeRatio = parameters.timeRatio[0];
    const vibDepth = parameters.vibratoDepth[0];
    const vibRate = parameters.vibratoRate[0];
    const tremDepth = parameters.tremoloDepth[0];
    const tremRate = parameters.tremoloRate ? parameters.tremoloRate[0] : 0;
    const gateDepth = parameters.gateDepth ? parameters.gateDepth[0] : 0;
    const gateRate = parameters.gateRate ? parameters.gateRate[0] : 4.0;
    const bitcrushAmount = parameters.bitcrush ? parameters.bitcrush[0] : 0.0;
    const spectralComp = parameters.spectralComp ? parameters.spectralComp[0] : 0.0;
    const subHarmonicsAmount = parameters.subHarmonics ? parameters.subHarmonics[0] : 0.0;
    const vocalChorusAmount = parameters.vocalChorus ? parameters.vocalChorus[0] : 0.0;
    const downsampleFactor = parameters.downsample ? parameters.downsample[0] : 1.0;
    const breath = parameters.breathIntensity[0];
    const drumDuckDepth = parameters.drumDuckDepth ? parameters.drumDuckDepth[0] : 0.0;

    const pitchAttack = parameters.pitchAttack ? parameters.pitchAttack[0] : 0.0;
    const pitchDecay = parameters.pitchDecay ? parameters.pitchDecay[0] : 0.0;
    const pitchAmount = parameters.pitchAmount ? parameters.pitchAmount[0] : 0.0;
    const attack = parameters.attack ? parameters.attack[0] : 0.05;
    const decay = parameters.decay ? parameters.decay[0] : 0.1;
    const sustain = parameters.sustain ? parameters.sustain[0] : 1.0;
    const release = parameters.release ? parameters.release[0] : 0.1;

    let currentVibDepth = vibDepth;
    let currentVibRate = vibRate;
    if (this.isPlaying && this.fullSampleBuffer && this.phonemeData && this.phonemeRatios) {
        const pData = this.getPhonemeDataAtSample(this.currentSamplePtr);
        const pVibDepth = pData[3];
        const pVibRate = pData[4];
        if (pVibDepth !== -1.0) currentVibDepth = pVibDepth;
        if (pVibRate !== -1.0) currentVibRate = pVibRate;
    }

    // Drum sidechain envelope follower
    const fsForDuck = resolveWorkletSampleRate({ sampleRate: this.sampleRate || globalThis.sampleRate });
    const { duckingScalar, isSnare: drumIsSnare } = this.drumDuck.process(
      this.drumSidechainSAB, drumDuckDepth, currentTime, blockFrames, fsForDuck
    );

    this.expressiveProcessor.updateConfig({
      vibrato: { depth: currentVibDepth, rate: currentVibRate, enabled: currentVibDepth > 0 },
      tremolo: { depth: tremDepth, rate: tremRate, enabled: tremDepth > 0 },
      gate: { depth: gateDepth, rate: gateRate, enabled: gateDepth > 0 },
      breath: { amount: breath, enabled: breath > 0, filterCutoff: 2000 },

      envelope: { attack, decay, sustain, release },
      pitchEnvelope: { attack: pitchAttack, decay: pitchDecay, amount: pitchAmount }

    });

    // Combine note pitch with parameter modulation
    let finalPitch = this.isPlaying ? this.basePitch * pitch : pitch;


    // Apply Pitch Envelope
    if (pitchAmount !== 0.0 && pitchEnvelopeValue > 0.0) {
      // Amount is in semitones. Pitch envelope value is 0.0 to 1.0.
      const pitchEnvSemitones = pitchAmount * pitchEnvelopeValue;
      const pitchEnvRatio = Math.pow(2.0, pitchEnvSemitones / 12.0);
      finalPitch *= pitchEnvRatio;
    }

    // Granular Pitch Shift & Envelope
    let granularPitchShift = parameters.granularPitchShift ? parameters.granularPitchShift[0] : 0.0;

    // Apply Granular Pitch Envelope (maps envelope 0-1 to shift amount, similar to main pitch env)
    const grainPitchEnvDepth = parameters.grainPitchEnvDepth ? parameters.grainPitchEnvDepth[0] : 0.0;
    if (grainPitchEnvDepth !== 0.0 && pitchEnvelopeValue > 0.0) {
        const maxEnvShift = 24.0;
        granularPitchShift += (maxEnvShift * grainPitchEnvDepth * pitchEnvelopeValue);
    }

    if (granularPitchShift !== 0.0) {
      const pitchShiftRatio = Math.pow(2.0, granularPitchShift / 12.0);
      finalPitch *= pitchShiftRatio;
    }

    // Apply Phoneme Pitch Bend (if we're streaming from a buffer and have it calculated)
    if (this.isPlaying && this.fullSampleBuffer && this.phonemeData && this.phonemeRatios) {
        const pData = this.getPhonemeDataAtSample(this.currentSamplePtr);
        const pBend = pData[2];
        if (pBend !== 0.0) {
            const pitchBendRatio = Math.pow(2.0, pBend / 1200.0);
            finalPitch *= pitchBendRatio;
        }
    }

    // Pitch Correction (AutoTune)
    const autoTuneAmount = parameters.autoTune ? parameters.autoTune[0] : 0.0;
    const sRate = resolveWorkletSampleRate({ sampleRate: this.sampleRate || globalThis.sampleRate });

    if (autoTuneAmount > 0.0 && this.isPlaying && this.fullSampleBuffer && this.targetHz > 0) {
      const pData = this.getPhonemeDataAtSample(this.currentSamplePtr);
      const isVowel = pData[7] > 0;

      // Only attempt detection on voiced vowels with sufficient envelope
      if (isVowel && envelopeValue > 0.01) {
        // Fast zero-crossing period detector on the input buffer slice
        const searchFrames = Math.min(1024, this.fullSampleBuffer.length - this.currentSamplePtr);
        const minPeriod = Math.floor(sRate / 400); // 400 Hz max
        const maxPeriod = Math.floor(sRate / 70);  // 70 Hz min

        let crosses = 0;

        for (let i = 0; i < searchFrames; i++) {
          const idx = this.currentSamplePtr + i;
          const x = this.fullSampleBuffer[idx];

          // Hysteresis threshold to avoid noise false triggers
          if (x > 0.02 && this.pitchDetectState.lastSample <= 0.02) {
            // Positive edge crossing
            const currentCrossIndex = idx;
            if (this.pitchDetectState.lastCrossIndex > 0) {
              const period = currentCrossIndex - this.pitchDetectState.lastCrossIndex;
              if (period >= minPeriod && period <= maxPeriod) {
                 this.pitchDetectState.periods[this.pitchDetectState.periodIndex] = period;
                 this.pitchDetectState.periodIndex = (this.pitchDetectState.periodIndex + 1) % 5;
                 crosses++;
                 // We only need one valid period to update the state, but we can search for a few to fill the median buffer quickly if empty
                 if (crosses >= 2) break;
              }
            }
            this.pitchDetectState.lastCrossIndex = currentCrossIndex;
          }
          this.pitchDetectState.lastSample = x;
        }

        // Calculate median period if we have valid data
        let validPeriods = 0;
        let sum = 0;
        for (let i = 0; i < 5; i++) {
          if (this.pitchDetectState.periods[i] > 0) {
             validPeriods++;
             sum += this.pitchDetectState.periods[i];
          }
        }

        if (validPeriods > 0) {
           const avgPeriod = sum / validPeriods;
           this.pitchDetectState.lastValidF0 = sRate / avgPeriod;
        }
      }

      // Apply correction based on last valid F0 (held during consonants)
      if (this.pitchDetectState.lastValidF0 > 0) {
         const rawCorr = Math.max(0.5, Math.min(2.0, this.targetHz / this.pitchDetectState.lastValidF0));
         const corr = 1.0 + autoTuneAmount * (rawCorr - 1.0);

         // Medium-fast block rate smoothing (alpha ~0.2)
         this.pitchDetectState.smoothCorr = this.pitchDetectState.smoothCorr * 0.8 + corr * 0.2;
         finalPitch *= this.pitchDetectState.smoothCorr;
      } else {
         // Decay back to 1.0 if no valid F0 ever detected
         this.pitchDetectState.smoothCorr = this.pitchDetectState.smoothCorr * 0.8 + 1.0 * 0.2;
         finalPitch *= this.pitchDetectState.smoothCorr;
      }
    } else {
      // Decay back to 1.0 if bypassed
      this.pitchDetectState.smoothCorr = this.pitchDetectState.smoothCorr * 0.8 + 1.0 * 0.2;
      finalPitch *= this.pitchDetectState.smoothCorr;

      // Granular Pitch Quantization: snap pitch to intervals when active (only if autoTune is off to prevent fighting)
      const grainPitchQuantize = parameters.grainPitchQuantize ? parameters.grainPitchQuantize[0] : 0.0;
      if (grainPitchQuantize > 0.0 && finalPitch > 0.0) {
        const semitones = 12.0 * Math.log2(finalPitch);
        const quantizedSemitones = Math.round(semitones / grainPitchQuantize) * grainPitchQuantize;
        finalPitch = Math.pow(2.0, quantizedSemitones / 12.0);
      }
    }

    // Apply Auto-Tune Pitch Correction based on previous block's detected pitch
    const autoTune = parameters.autoTune ? parameters.autoTune[0] : 0.0;
    if (autoTune > 0.0 && this.autoTuneSmoothedPeriod > 0) {
      const fs = resolveWorkletSampleRate({ sampleRate: this.sampleRate || globalThis.sampleRate });
      const detectedFreq = fs / this.autoTuneSmoothedPeriod;

      // Quantize detected frequency to nearest MIDI note
      if (detectedFreq > 20 && detectedFreq < 20000) {
        const midiNote = 12.0 * Math.log2(detectedFreq / 440.0) + 69.0;
        const nearestMidiNote = Math.round(midiNote);
        const targetFreq = 440.0 * Math.pow(2.0, (nearestMidiNote - 69.0) / 12.0);

        const correctionRatio = targetFreq / detectedFreq;

        // Blend between uncorrected and fully corrected based on autoTune depth
        finalPitch *= (1.0 - autoTune) + (autoTune * correctionRatio);
      }
    }

    this.rubberBand.setPitchScale(finalPitch);

    try {
      // STREAMING INPUT LOGIC
      // If playing a note, stream from fullSampleBuffer with phoneme-aware time stretching
      if (this.isPlaying && this.fullSampleBuffer) {
        // Calculate dynamic time ratio based on phoneme data
        let ratio = defaultTimeRatio;
        if (this.phonemeData && this.phonemeRatios) {
          const pData = this.getPhonemeDataAtSample(this.currentSamplePtr);
          const pRatio = pData[0];
          ratio = pRatio;
        }

        // Apply Time-Stretch Envelope modulation
        const timeStretchEnvDepth = parameters.timeStretchEnvDepth ? parameters.timeStretchEnvDepth[0] : 0.0;
        const timeModulation = timeStretchEnvDepth * envelopeValue * 3.0; // scale factor
        ratio = Math.max(0.1, Math.min(4.0, ratio + timeModulation));

        this.rubberBand.setTimeRatio(ratio);

        const samplesRequired = this.rubberBand.getSamplesRequired();

        const freezeBase = parameters.freeze ? parameters.freeze[0] : 0.0;
        const freezeLfoRate = parameters.freezeLfoRate ? parameters.freezeLfoRate[0] : 0.0;
        const freezeLfoDepth = parameters.freezeLfoDepth ? parameters.freezeLfoDepth[0] : 0.0;
        const freezeEnvDepth = parameters.freezeEnvDepth ? parameters.freezeEnvDepth[0] : 0.0;
        const grainEnvDepth = parameters.grainEnvDepth ? parameters.grainEnvDepth[0] : 0.0;
        const windowShape = parameters.windowShape ? parameters.windowShape[0] : 0.0;
        const grainLfoRate = parameters.grainLfoRate ? parameters.grainLfoRate[0] : 0.0;
        const grainLfoDepth = parameters.grainLfoDepth ? parameters.grainLfoDepth[0] : 0.0;
        const grainPosLfoDepth = parameters.grainPosLfoDepth ? parameters.grainPosLfoDepth[0] : 0.0;

        // Advance LFO phase once per block (128 samples, standard Web Audio block size)
        const sRateFreeze = resolveWorkletSampleRate({ sampleRate: this.sampleRate || globalThis.sampleRate });
        const framesInBlock = 128;
        this.granular.advanceLfoPhases(freezeLfoRate, grainLfoRate, sRateFreeze, framesInBlock);

        const lfoValue = this.granular.getFreezeLfoValue();
        // Bipolar modulation: freezeBase + freezeLfoDepth * sin, plus envelope follower modulation
        let freezeAmt = freezeBase + (freezeLfoDepth * lfoValue) + (freezeEnvDepth * envelopeValue);
        freezeAmt = Math.max(0.0, Math.min(1.0, freezeAmt));

        const isFrozen = freezeAmt > 0.5;

        if (isFrozen) {
          this.granular.enterFreeze();

          // FREEZE STREAMING (Spectral Granulator)
          this.granular.renderFrozenBlock({
            rubberBand: this.rubberBand,
            ensureHeapSize: (frames) => this.ensureHeapSize(frames),
            getInputHeapPtr: () => this.inputHeapPtr,
            fullSampleBuffer: this.fullSampleBuffer,
            sampleRate: resolveWorkletSampleRate({ sampleRate: this.sampleRate || globalThis.sampleRate }),
            phonemeData: this.phonemeData,
            phonemeRatios: this.phonemeRatios,
            currentSamplePtr: this.currentSamplePtr,
            startSamplePtr: this.startSamplePtr,
            endSamplePtr: this.endSamplePtr,
            duckingScalar,
            envelopeValue,
            grainJitterParam: parameters.grainJitter ? parameters.grainJitter[0] : 0.0,
            grainEnvDepth,
            windowShape,
            grainLfoDepth,
            grainPosLfoDepth,
            samplesRequired
          });
        } else {
          const wasUnfrozen = this.granular.exitFreeze();
          if (wasUnfrozen) {
            // Clear SVF states to avoid bleed from panned grains
            this.spectral.clearLegacyBandState();
          }

          if (this.isReverse) {
            // REVERSE STREAMING
            const samplesRemaining = this.currentSamplePtr - this.startSamplePtr + 1;

            if (samplesRemaining > 0 && samplesRequired > 0) {
              const samplesToFeed = Math.min(samplesRemaining, samplesRequired);
              this.ensureHeapSize(samplesToFeed);

              // Manually copy in reverse order
              const heap = this.rubberBand.module.HEAPF32;
              const ptr = this.inputHeapPtr >> 2;
              const buf = this.fullSampleBuffer;
              let readPtr = this.currentSamplePtr;

              for (let i = 0; i < samplesToFeed; i++) {
                heap[ptr + i] = buf[readPtr--];
              }

              this.rubberBand.process(this.inputHeapPtr, samplesToFeed, false);
              this.currentSamplePtr = readPtr;
            }
          } else {
            // FORWARD STREAMING
            const samplesRemaining = this.endSamplePtr - this.currentSamplePtr;

            if (samplesRemaining > 0 && samplesRequired > 0) {
              const samplesToFeed = Math.min(samplesRemaining, samplesRequired);
              this.ensureHeapSize(samplesToFeed);

              // Copy directly to WASM heap
              const slice = this.fullSampleBuffer.subarray(
                this.currentSamplePtr,
                this.currentSamplePtr + samplesToFeed
              );
              this.rubberBand.module.HEAPF32.set(slice, this.inputHeapPtr >> 2);

              this.rubberBand.process(this.inputHeapPtr, samplesToFeed, false);
              this.currentSamplePtr += samplesToFeed;
            }
          }
        }
      }
      // Fallback: Check RingBuffer input (for real-time mic usage if supported later)
      else if (this.inputRingBuffer && this.inputRingBuffer.availableRead() > 0) {
        const required = this.rubberBand.getSamplesRequired();
        const available = this.inputRingBuffer.availableRead();
        if (available >= required && required > 0) {
          this.ensureHeapSize(required);
          const inputView = this.rubberBand.module.HEAPF32.subarray(
            this.inputHeapPtr >> 2, (this.inputHeapPtr >> 2) + required
          );
          this.inputRingBuffer.pull(inputView);
          this.rubberBand.process(this.inputHeapPtr, required, false);
        }
      }

      // --- OUTPUT RETRIEVAL LOGIC ---
      const availOutput = this.rubberBand.available();
      if (availOutput > 0) {
        const framesToRead = Math.min(availOutput, outputChannel.length);
        this.ensureHeapSize(framesToRead);

        const retrieved = this.rubberBand.retrieve(this.outputHeapPtr, framesToRead);
        const outputView = this.rubberBand.module.HEAPF32.subarray(
          this.outputHeapPtr >> 2,
          (this.outputHeapPtr >> 2) + retrieved
        );

        outputChannel.set(outputView);
        this.expressiveProcessor.process(outputChannel, outputChannel);

        // Zero-Crossing Pitch Detection for Auto-Tune
        if (autoTune > 0.0 && outputChannel.length > 0) {
            for (let i = 0; i < outputChannel.length; i++) {
                const sample = outputChannel[i];
                const currentSign = sample >= 0 ? 1 : -1;

                this.autoTuneSamplesSinceZero++;

                if (currentSign !== this.autoTuneLastSign) {
                    if (currentSign === 1) { // Positive edge
                        if (this.autoTuneSamplesSinceZero > 10) { // Filter out very high freq noise (> ~4kHz)
                            const currentPeriod = this.autoTuneSamplesSinceZero;
                            if (this.autoTuneSmoothedPeriod === 0) {
                                this.autoTuneSmoothedPeriod = currentPeriod;
                            } else {
                                // Smooth the period measurement
                                this.autoTuneSmoothedPeriod = this.autoTuneSmoothedPeriod * 0.9 + currentPeriod * 0.1;
                            }
                        }
                        this.autoTuneSamplesSinceZero = 0;
                    }
                    this.autoTuneLastSign = currentSign;
                }
            }
        }

        // Apply phoneme volume and filter mod
        const phonemeFilterMod = parameters.phonemeFilterMod ? parameters.phonemeFilterMod[0] : 0.0;
        const hasPhonemeContext = this.isPlaying && !!this.fullSampleBuffer && !!this.phonemeData && !!this.phonemeRatios;
        const phonemeVolume = hasPhonemeContext ? this.getPhonemeDataAtSample(this.currentSamplePtr)[1] : null;
        const sRateForPhonemeFilter = resolveWorkletSampleRate({ sampleRate: this.sampleRate || globalThis.sampleRate });
        this.phonemeToneFilter.process(outputChannel, phonemeFilterMod, phonemeVolume, sRateForPhonemeFilter);

        // Apply Syllable Volume Filter
        const volFilterMod = parameters.volumeFilterMod ? parameters.volumeFilterMod[0] : 0.0;
        if (volFilterMod > 0 && this.isPlaying && this.phonemeData) {
          const pData = this.getPhonemeDataAtSample(this.currentSamplePtr);
          this.syllableVolumeFilter.process(outputs, volFilterMod, pData[1], pData[7], this.sampleRate);
        }

        // Apply Rhythmic Gating (Trance Gate)
        const sRateForGate = resolveWorkletSampleRate({ sampleRate: this.sampleRate || globalThis.sampleRate });
        this.tranceGate.process(outputChannel, gateDepth, gateRate, sRateForGate);

        // Grain-triggered stereo pan spread
        const grainPanSpread = parameters.grainPanSpread ? parameters.grainPanSpread[0] : 0.0;
        const spectralCompression = parameters.spectralCompression
          ? parameters.spectralCompression[0]
          : 0.0;
        const isVowelForPan = (grainPanSpread > 0 && this.granular.grainWrapPending)
          ? this.getPhonemeDataAtSample(this.currentSamplePtr)[7]
          : 0;
        this.granular.updateGrainPan(grainPanSpread, isVowelForPan);

        const outL = outputs[0][0];
        const outR = outputs[0][1];
        const hasStereo = !!(outL && outR);
        const sRateForSpectral = resolveWorkletSampleRate({ sampleRate: this.sampleRate || globalThis.sampleRate });

        this.spectral.applyBandSplitAndCompression({
          outL,
          outR,
          hasStereo,
          spectralComp,
          spectralCompression,
          grainPanSpread,
          grainPanL: this.granular.grainPanL,
          grainPanR: this.granular.grainPanR,
          sampleRate: sRateForSpectral
        });

        this.spectral.applyLegacyCompressor({
          outputs,
          hasStereo,
          outL,
          spectralComp,
          sampleRate: sRateForSpectral
        });

        // Vocal Stack Chorus Effect (Post-Retrieve Micro-Delay Taps)
        if (vocalChorusAmount > 0) {
          const isVowelForChorus = this.getPhonemeDataAtSample(this.currentSamplePtr)[7];
          const fsForChorus = this.sampleRate || (globalThis as { sampleRate?: number }).sampleRate || 44100;
          this.chorus.process(outputs, vocalChorusAmount, isVowelForChorus, fsForChorus);
        }

        // Generate Sub-Harmonics (Vowels only)
        // Duck sub harmonics heavily on Kick (drumIsSnare === 0)
        const effectiveSubAmount = subHarmonicsAmount * (drumIsSnare === 0.0 ? Math.max(0, 1.0 - duckingScalar) : 1.0);
        if (effectiveSubAmount > 0) {
          const isVowelForSub = this.getPhonemeDataAtSample(this.currentSamplePtr)[7];
          const sRateForSub = resolveWorkletSampleRate({ sampleRate: this.sampleRate || globalThis.sampleRate });
          this.subHarmonics.process(outputs, effectiveSubAmount, isVowelForSub, sRateForSub);
        }

        if (duckingScalar > 0) {
          const isVowelForDuck = this.getPhonemeDataAtSample(this.currentSamplePtr)[7];
          this.drumDuck.applyMasterDuck(outputs, duckingScalar, isVowelForDuck);
        }

        // Apply Bitcrush & Downsample
        this.bitcrusher.process(outputs, bitcrushAmount, downsampleFactor);

        // Check for completion when no output is available but we're still marked as playing
        if (this.isReverse) {
          if (this.currentSamplePtr < this.startSamplePtr) this.isPlaying = false;
        } else {
          if (this.currentSamplePtr >= this.endSamplePtr) this.isPlaying = false;
        }
      }

    } catch (e) {
      console.error("DSP Error:", e);
    }

    return true;
    } finally {
      this.perf.endProcess();
    }
  }

  private ensureHeapSize(frames: number) {
    if (frames > this.heapSizeFrames) {
      if (this.inputHeapPtr) this.rubberBand.module._free(this.inputHeapPtr);
      if (this.outputHeapPtr) this.rubberBand.module._free(this.outputHeapPtr);

      this.inputHeapPtr = this.rubberBand.module._malloc(frames * 4);
      this.outputHeapPtr = this.rubberBand.module._malloc(frames * 4);
      this.heapSizeFrames = frames;
    }
  }
}

registerProcessor('RubberBandProcessor', RubberBandProcessor);
