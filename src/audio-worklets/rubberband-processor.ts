interface AudioWorkletProcessor {
  readonly port: MessagePort;
  process(inputs: Float32Array[][], outputs: Float32Array[][], parameters: Record<string, Float32Array>): boolean;
}

declare var AudioWorkletProcessor: {
  prototype: AudioWorkletProcessor;
  new(options?: any): AudioWorkletProcessor;
};

declare function registerProcessor(name: string, processorCtor: (new (options?: any) => AudioWorkletProcessor)): void;

// RealTime (1) | Finer (32) | FormantPreserved (1048576)
const DEFAULT_STRETCHER_OPTIONS = 1 | 32 | 1048576;

/** Rubber Band option bits for a 'setStretchProfile' profile name. */
function stretcherOptionsFor(profile: string): number {
  if (profile === 'harmonic') return 1 | 32 | 256 | 0x02000000; // RealTime | Finer | TransientsMixed | PitchHighQuality
  if (profile === 'fast') return 1; // RealTime | Faster
  return 1 | 32 | 256 | 1048576; // RealTime | Finer | TransientsMixed | FormantPreserved
}

const param = (parameters: Record<string, Float32Array>, name: string, fallback: number): number =>
  parameters[name] ? parameters[name][0] : fallback;

/**
 * Singing-voice worklet: streams the loaded sample (forward, reverse or
 * frozen through the granulator) into the Rubber Band stretcher, then runs
 * the retrieved block through the expressive processor and the vocal FX
 * chain. The DSP lives in rubberband.wasm (stretcher + rb_fx_*); this class
 * schedules it and owns the message contract.
 */
class RubberBandProcessor extends AudioWorkletProcessor {
  private rubberBand: any = null;
  private inputRingBuffer: RingBuffer | null = null;
  private outputRingBuffer: RingBuffer | null = null;
  private expressiveProcessor: ExpressiveVoiceProcessor;
  private readonly perf = new WorkletPerfReporter(this.port, 'rubberband');

  private readonly drumDuck = new DrumDuckEnvelope();
  private readonly pitch = new PitchController();

  // Singing-voice FX chain. Native (rb_fx_* in rubberband.wasm) once INIT_WASM
  // finds the exports; the TS chain only until then, or as a reported fallback.
  private fx: VocalFxChain;
  private readonly fxBlock = createVocalFxBlock();
  private customWindowShape: Float32Array | null = null;
  private customGrainEnvelope: number[] | null = null;
  // The node is created with outputChannelCount [2]; this only backs a mono host.
  private readonly fxScratchRight = new Float32Array(128);

  // Pre-allocated configuration for expressive processor to avoid per-block GC allocations
  private readonly currentExpressiveConfig = {
    vibrato: { depth: 0, rate: 0, enabled: false },
    tremolo: { depth: 0, rate: 0, enabled: false },
    gate: { depth: 0, rate: 0, enabled: false },
    breath: { amount: 0, enabled: false, filterCutoff: 2000 },
    envelope: { attack: 0, decay: 0, sustain: 0, release: 0 },
    pitchEnvelope: { attack: 0, decay: 0, amount: 0 }
  };

  private readonly pitchContext: PitchContext = {
    playing: false,
    basePitch: 1,
    targetHz: 0,
    sampleRate: 0,
    envelopeValue: 0,
    pitchEnvelopeValue: 0,
    fullSampleBuffer: null,
    currentSamplePtr: 0,
    phoneme: null,
  };

  // WASM Memory Management
  private inputHeapPtr: number = 0;
  private outputHeapPtr: number = 0;
  private heapSizeFrames: number = 0;

  // Audio State
  private sampleRate = 44100;
  private initialized = false;
  private fullSampleBuffer: Float32Array | null = null;

  // Phoneme Data (stride-10 SAB + per-phoneme stretch ratios; see phonemeData.ts)
  private phonemeData: Float32Array | null = null;
  private phonemeRatios: number[] | null = null;
  private readonly phonemeTuple = new Float32Array(9);

  // Drum Envelope Sidechain
  private drumSidechainSAB: Float32Array | null = null;

  // Playback State (Unified)
  private isPlaying = false;
  private isReverse = false;

  private currentSamplePtr = 0;
  private startSamplePtr = 0;
  private endSamplePtr = 0;
  private basePitch = 1.0;
  private targetHz: number = 0;

  static get parameterDescriptors() {
    return RUBBERBAND_PARAMETER_DESCRIPTORS;
  }

  constructor() {
    super();
    this.port.onmessage = this.handleMessage.bind(this);
    this.sampleRate = resolveWorkletSampleRate();

    this.expressiveProcessor = new ExpressiveVoiceProcessor({
      sampleRate: this.sampleRate
    });
    this.fx = new TsVocalFx(this.sampleRate);
  }

  /** Swaps the FX chain, replaying the sample buffer and grain windows into it. */
  private useFxChain(next: VocalFxChain): void {
    this.fx.dispose();
    this.fx = next;
    if (this.fullSampleBuffer) next.setSampleBuffer(this.fullSampleBuffer);
    if (this.customWindowShape) next.setCustomWindowShape(this.customWindowShape);
    if (this.customGrainEnvelope) next.setCustomGrainEnvelope(this.customGrainEnvelope);
  }

  /** Picks the FX backend for a freshly loaded module; never falls back silently. */
  private selectFxChain(module: unknown, requested: VocalFxBackend): { backend: VocalFxBackend; reason?: string } {
    if (requested === 'ts') {
      this.useFxChain(new TsVocalFx(this.sampleRate));
      return { backend: 'ts', reason: 'forced by fxBackend=ts' };
    }
    const probe = probeNativeVocalFx(module);
    if (!probe.ok) {
      this.useFxChain(new TsVocalFx(this.sampleRate));
      return { backend: 'ts', reason: probe.reason };
    }
    try {
      this.useFxChain(new NativeVocalFx(probe.module, this.sampleRate));
      return { backend: 'native' };
    } catch (e) {
      this.useFxChain(new TsVocalFx(this.sampleRate));
      return { backend: 'ts', reason: `native FX init failed: ${String(e)}` };
    }
  }

  /** Mid-session native failure: continue on the TS chain and tell the host. */
  private fallBackToTsFx(reason: string): void {
    try {
      this.useFxChain(new TsVocalFx(this.sampleRate));
    } catch (e) {
      console.error("[RubberBandProcessor] TS FX fallback failed:", e);
    }
    this.port.postMessage({ type: 'FX_BACKEND', backend: 'ts', reason });
  }

  async handleMessage(event: MessageEvent) {
    const { type, data } = event.data;

    switch (type) {
      case 'INIT_WASM':
        try {
          const { inputBuffer, outputBuffer, wasmBinary, baseUrl, drumSidechainSAB, fxBackend } = event.data;

          this.inputRingBuffer = new RingBuffer(inputBuffer);
          this.outputRingBuffer = new RingBuffer(outputBuffer);

          if (drumSidechainSAB) {
            this.drumSidechainSAB = new Float32Array(drumSidechainSAB);
          }

          if (!wasmBinary) {
            throw new Error("WASM binary not provided in INIT_WASM message");
          }

          const wasmPath = `${baseUrl || '/'}rubberband.wasm`;
          // Instantiate WASM module with the provided binary
          // @ts-ignore
          const module = await createRubberBandModule({
            wasmBinary: wasmBinary,
            locateFile: (path: string) => {
              if (path.endsWith('.wasm')) return wasmPath;
              return path;
            }
          });

          const safeSampleRate = Math.floor(resolveWorkletSampleRate({ sampleRate: this.sampleRate }));

          console.log(`[RubberBandProcessor] Initializing with: Rate=${safeSampleRate}, Ch=1, Opts=${DEFAULT_STRETCHER_OPTIONS}`);

          this.rubberBand = new module.RubberBandStretcher(
            safeSampleRate,
            1, // Mono
            DEFAULT_STRETCHER_OPTIONS,
            1.0, // Initial Time Ratio
            1.0  // Initial Pitch Scale
          );

          this.rubberBand.module = module;
          const fx = this.selectFxChain(module, fxBackend === 'ts' ? 'ts' : 'native');
          if (fx.backend === 'ts') {
            console.warn(`[RubberBandProcessor] Vocal FX on TypeScript fallback: ${fx.reason}`);
          }
          this.initialized = true;
          this.port.postMessage({ type: 'READY', fxBackend: fx.backend, fxReason: fx.reason });
        } catch (e) {
          console.error("RubberBand WASM Failed:", e);
          this.port.postMessage({ type: 'ERROR', error: String(e) });
        }
        break;

      case 'loadBuffer':
        if (data && data.buffer) {
          this.fullSampleBuffer = new Float32Array(data.buffer);
          try {
            this.fx.setSampleBuffer(this.fullSampleBuffer);
          } catch (e) {
            if (this.fx.backend !== 'native') throw e;
            this.fallBackToTsFx(`native FX could not take the sample buffer: ${String(e)}`);
          }
        }
        break;

      case 'setCustomWindowShape':
        this.customWindowShape = data.shape && data.shape.length > 0 ? new Float32Array(data.shape) : null;
        this.fx.setCustomWindowShape(this.customWindowShape);
        break;

      case 'setPhonemeData':
        if (data && data.sharedBuffer) {
          this.phonemeData = new Float32Array(data.sharedBuffer);
          this.phonemeRatios = data.ratios || null;
        }
        break;

      case 'noteOn': {
        if (!this.initialized || !this.fullSampleBuffer || !data) return;
        this.rubberBand.reset();

        // Store base pitch for combination with parameters
        this.basePitch = data.pitch || 1.0;
        if (data.targetHz) {
          this.targetHz = data.targetHz;
        }
        this.fxBlock.velocity = data.velocity ?? 1.0;
        this.rubberBand.setPitchScale(this.basePitch);
        this.rubberBand.setTimeRatio(1.0);
        this.expressiveProcessor.reset();
        this.expressiveProcessor.noteOn();

        const startSample = Math.max(0, Math.floor(data.startSample || 0));
        const endSample = data.endSample
          ? Math.min(this.fullSampleBuffer.length, Math.floor(data.endSample))
          : this.fullSampleBuffer.length;

        if (startSample >= endSample) return;

        this.startSamplePtr = startSample;
        this.endSamplePtr = endSample;
        this.isReverse = !!data.reverse;
        this.currentSamplePtr = this.isReverse ? endSample - 1 : startSample;

        this.isPlaying = true;
        this.fx.noteOn();
        break;
      }

      case 'setReverse':
        if (data && typeof data.reverse === 'boolean') {
          this.isReverse = data.reverse;
        }
        break;

      case 'noteOff':
        this.expressiveProcessor.noteOff(data?.time);
        break;

      case 'setStretchProfile':
        // Update RubberBand quality options (requires a new stretcher)
        if (data && typeof data.profile === 'string' && this.rubberBand) {
          const timeRatio = this.rubberBand.getTimeRatio();
          const pitchScale = this.rubberBand.getPitchScale();

          // Free old buffers if they exist
          if (this.inputHeapPtr) this.rubberBand.module._free(this.inputHeapPtr);
          if (this.outputHeapPtr) this.rubberBand.module._free(this.outputHeapPtr);
          this.inputHeapPtr = 0;
          this.outputHeapPtr = 0;
          this.heapSizeFrames = 0;

          const module = this.rubberBand.module;
          this.rubberBand = new module.RubberBandStretcher(
            this.sampleRate, 1, stretcherOptionsFor(data.profile), 1.0, 1.0
          );
          this.rubberBand.module = module;
          this.rubberBand.setTimeRatio(timeRatio);
          this.rubberBand.setPitchScale(pitchScale);
        }
        break;

      case 'setAutoFollow':
        // Accepted for contract compatibility; auto pitch follow is not implemented.
        break;

      case 'setCustomGrainEnvelope':
        this.customGrainEnvelope = data && Array.isArray(data.shape) ? data.shape : null;
        this.fx.setCustomGrainEnvelope(this.customGrainEnvelope);
        break;
    }
  }

  /** Phoneme tuple at the read position (defaults without phoneme data). */
  private phonemeAt(): Float32Array {
    return getPhonemeDataAtSample(this.phonemeData, this.phonemeRatios, this.currentSamplePtr, this.phonemeTuple);
  }

  /** True while streaming a note that carries phoneme data + ratios. */
  private hasPhonemeContext(): boolean {
    return this.isPlaying && !!this.fullSampleBuffer && !!this.phonemeData && !!this.phonemeRatios;
  }

  /** Copies the phoneme tuple at the current read position into the FX block. */
  private fillPhonemeFx(block: VocalFxBlock): Float32Array {
    const pData = this.phonemeAt();
    block.hasPhonemeContext = this.hasPhonemeContext();
    block.phonemeVolume = pData[1];
    block.isVowel = pData[7];
    block.phonemeGrainJitter = pData[5];
    block.phonemeGrainSizeMs = pData[6];
    return pData;
  }

  process(_inputs: Float32Array[][], outputs: Float32Array[][], parameters: Record<string, Float32Array>): boolean {
    const outputChannel = outputs[0][0];
    const blockFrames = outputChannel?.length ?? 128;
    this.perf.beginProcess(blockFrames);
    try {
    outputChannel.fill(0);

    if (!this.initialized || !this.rubberBand || !this.outputRingBuffer) {
      return true;
    }

    // Block start time on the audio clock, for the expressive envelopes.
    // @ts-ignore - AudioWorkletGlobalScope.currentTime
    const currentTime = typeof globalThis.currentTime === 'number' ? globalThis.currentTime : 0;
    this.expressiveProcessor.setCurrentTime(currentTime);

    const envelopeValue = this.expressiveProcessor.getCurrentEnvelopeValue();
    const pitchEnvelopeValue = this.expressiveProcessor.getCurrentPitchEnvelopeValue();

    const gateDepth = param(parameters, 'gateDepth', 0);
    const gateRate = param(parameters, 'gateRate', 4.0);
    const tremDepth = parameters.tremoloDepth[0];
    const breath = parameters.breathIntensity[0];

    // Per-phoneme vibrato overrides the global vibrato
    const phoneme = this.hasPhonemeContext() ? this.phonemeAt() : null;
    let currentVibDepth = parameters.vibratoDepth[0];
    let currentVibRate = parameters.vibratoRate[0];
    if (phoneme) {
      if (phoneme[3] !== -1.0) currentVibDepth = phoneme[3];
      if (phoneme[4] !== -1.0) currentVibRate = phoneme[4];
    }

    // Drum sidechain envelope follower
    const { duckingScalar, isSnare: drumIsSnare } = this.drumDuck.process(
      this.drumSidechainSAB, param(parameters, 'drumDuckDepth', 0.0), currentTime, blockFrames, this.sampleRate
    );

    const cfg = this.currentExpressiveConfig;
    cfg.vibrato.depth = currentVibDepth;
    cfg.vibrato.rate = currentVibRate;
    cfg.vibrato.enabled = currentVibDepth > 0;
    cfg.tremolo.depth = tremDepth;
    cfg.tremolo.rate = param(parameters, 'tremoloRate', 0);
    cfg.tremolo.enabled = tremDepth > 0;
    cfg.gate.depth = gateDepth;
    cfg.gate.rate = gateRate;
    cfg.gate.enabled = gateDepth > 0;
    cfg.breath.amount = breath;
    cfg.breath.enabled = breath > 0;
    cfg.envelope.attack = param(parameters, 'attack', 0.05);
    cfg.envelope.decay = param(parameters, 'decay', 0.1);
    cfg.envelope.sustain = param(parameters, 'sustain', 1.0);
    cfg.envelope.release = param(parameters, 'release', 0.1);
    cfg.pitchEnvelope.attack = param(parameters, 'pitchAttack', 0.0);
    cfg.pitchEnvelope.decay = param(parameters, 'pitchDecay', 0.0);
    cfg.pitchEnvelope.amount = param(parameters, 'pitchAmount', 0.0);
    this.expressiveProcessor.updateConfig(cfg);

    const pc = this.pitchContext;
    pc.playing = this.isPlaying;
    pc.basePitch = this.basePitch;
    pc.targetHz = this.targetHz;
    pc.sampleRate = this.sampleRate;
    pc.envelopeValue = envelopeValue;
    pc.pitchEnvelopeValue = pitchEnvelopeValue;
    pc.fullSampleBuffer = this.fullSampleBuffer;
    pc.currentSamplePtr = this.currentSamplePtr;
    pc.phoneme = phoneme;
    this.rubberBand.setPitchScale(this.pitch.compute(pc, parameters));

    try {
      // STREAMING INPUT LOGIC
      // If playing a note, stream from fullSampleBuffer with phoneme-aware time stretching
      if (this.isPlaying && this.fullSampleBuffer) {
        // Per-phoneme ratio (target fit × elasticity) replaces the timeRatio param
        let ratio = parameters.timeRatio[0];
        if (this.phonemeData && this.phonemeRatios) {
          ratio = this.phonemeAt()[0];
        }

        // Apply Time-Stretch Envelope modulation
        const timeModulation = param(parameters, 'timeStretchEnvDepth', 0.0) * envelopeValue * 3.0;
        ratio = Math.max(0.1, Math.min(4.0, ratio + timeModulation));
        this.rubberBand.setTimeRatio(ratio);

        const samplesRequired = this.rubberBand.getSamplesRequired();

        // Freeze LFO advances once per 128-frame block
        const lfoValue = this.fx.advanceLfo(param(parameters, 'freezeLfoRate', 0.0), param(parameters, 'grainLfoRate', 0.0), 128);
        // Bipolar modulation: freezeBase + freezeLfoDepth * sin, plus envelope follower modulation
        const freezeAmt = Math.max(0.0, Math.min(1.0,
          param(parameters, 'freeze', 0.0)
          + param(parameters, 'freezeLfoDepth', 0.0) * lfoValue
          + param(parameters, 'freezeEnvDepth', 0.0) * envelopeValue
        ));

        if (freezeAmt > 0.5) {
          this.renderFrozen(parameters, samplesRequired, duckingScalar, envelopeValue);
        } else {
          this.fx.exitFreeze();
          this.streamSample(samplesRequired);
        }
      }
      // Fallback: Check RingBuffer input (for real-time mic usage if supported later)
      else if (this.inputRingBuffer && this.inputRingBuffer.availableRead() > 0) {
        const required = this.rubberBand.getSamplesRequired();
        const available = this.inputRingBuffer.availableRead();
        if (available >= required && required > 0) {
          this.ensureHeapSize(required);
          this.inputRingBuffer.pull(this.rubberBand.module.HEAPF32, this.inputHeapPtr >> 2);
          this.rubberBand.process(this.inputHeapPtr, required, false);
        }
      }

      // --- OUTPUT RETRIEVAL LOGIC ---
      const availOutput = this.rubberBand.available();
      if (availOutput > 0) {
        const framesToRead = Math.min(availOutput, outputChannel.length);
        this.ensureHeapSize(framesToRead);

        const retrieved = this.rubberBand.retrieve(this.outputHeapPtr, framesToRead);
        const heap = this.rubberBand.module.HEAPF32;
        const ptr = this.outputHeapPtr >> 2;
        for (let i = 0; i < retrieved; i++) {
          outputChannel[i] = heap[ptr + i];
        }

        const isVowelForExpressive = this.phonemeData && this.phonemeRatios ? this.phonemeAt()[7] : 1.0;
        this.expressiveProcessor.process(outputChannel, outputChannel, isVowelForExpressive);
        this.pitch.trackOutput(outputChannel, param(parameters, 'autoTune', 0.0));

        // Singing-voice FX chain (native rb_fx_process, or the reported TS fallback)
        const block = this.fxBlock;
        const pData = this.fillPhonemeFx(block);
        block.phonemeFilterMod = param(parameters, 'phonemeFilterMod', 0.0);
        const volFilterMod = param(parameters, 'volumeFilterMod', 0.0);
        block.volumeFilterMod = this.isPlaying && this.phonemeData ? volFilterMod : 0.0;
        block.syllableVolume = pData[1];
        block.gateDepth = gateDepth;
        block.gateRate = gateRate;
        block.spectralComp = param(parameters, 'spectralComp', 0.0);
        block.grainPanSpread = param(parameters, 'grainPanSpread', 0.0);
        block.vocalChorus = param(parameters, 'vocalChorus', 0.0);
        block.subHarmonics = param(parameters, 'subHarmonics', 0.0);
        block.duckingScalar = duckingScalar;
        block.drumIsSnare = drumIsSnare;
        block.bitcrush = param(parameters, 'bitcrush', 0.0);
        block.downsample = param(parameters, 'downsample', 1.0);

        const outR = outputs[0][1] ?? this.fxScratchRight;
        try {
          this.fx.process(block, outputChannel, outR);
        } catch (e) {
          if (this.fx.backend !== 'native') throw e;
          this.fallBackToTsFx(`native FX threw in rb_fx_process: ${String(e)}`);
        }

        // Check for completion when no output is available but we're still marked as playing
        if (this.isReverse) {
          if (this.currentSamplePtr < this.startSamplePtr) this.isPlaying = false;
        } else {
          if (this.currentSamplePtr >= this.endSamplePtr) this.isPlaying = false;
        }
      }

    } catch (e) {
      console.error("DSP Error:", e);
    }

    return true;
    } finally {
      this.perf.endProcess();
    }
  }

  /** Frozen block: the granulator writes the stretcher input in place of the sample stream. */
  private renderFrozen(
    parameters: Record<string, Float32Array>, samplesRequired: number, duckingScalar: number, envelopeValue: number,
  ): void {
    const block = this.fxBlock;
    this.fillPhonemeFx(block);
    block.duckingScalar = duckingScalar;
    block.envelopeValue = envelopeValue;
    block.grainJitter = param(parameters, 'grainJitter', 0.0);
    block.grainEnvDepth = param(parameters, 'grainEnvDepth', 0.0);
    block.windowShape = param(parameters, 'windowShape', 0.0);
    block.grainLfoDepth = param(parameters, 'grainLfoDepth', 0.0);
    block.grainPosLfoDepth = param(parameters, 'grainPosLfoDepth', 0.0);

    if (samplesRequired > 0) this.ensureHeapSize(samplesRequired);
    let toFeed = -1;
    try {
      toFeed = this.fx.renderGrains(
        block,
        this.rubberBand.module.HEAPF32,
        this.inputHeapPtr >> 2,
        samplesRequired,
        this.currentSamplePtr,
        this.startSamplePtr,
        this.endSamplePtr,
      );
    } catch (e) {
      if (this.fx.backend !== 'native') throw e;
      this.fallBackToTsFx(`native FX threw in rb_fx_render_grains: ${String(e)}`);
    }
    if (toFeed >= 0) {
      this.rubberBand.process(this.inputHeapPtr, toFeed, false);
    }
  }

  /** Feeds the stretcher from the sample buffer, forward or reversed, and advances the read pointer. */
  private streamSample(samplesRequired: number): void {
    const buf = this.fullSampleBuffer!;
    const samplesRemaining = this.isReverse
      ? this.currentSamplePtr - this.startSamplePtr + 1
      : this.endSamplePtr - this.currentSamplePtr;
    if (!(samplesRemaining > 0 && samplesRequired > 0)) return;

    const samplesToFeed = Math.min(samplesRemaining, samplesRequired);
    this.ensureHeapSize(samplesToFeed);
    const heap = this.rubberBand.module.HEAPF32;
    const ptr = this.inputHeapPtr >> 2;
    if (this.isReverse) {
      let readPtr = this.currentSamplePtr;
      for (let i = 0; i < samplesToFeed; i++) {
        heap[ptr + i] = buf[readPtr--];
      }
      this.currentSamplePtr = readPtr;
    } else {
      for (let i = 0; i < samplesToFeed; i++) {
        heap[ptr + i] = buf[this.currentSamplePtr + i];
      }
      this.currentSamplePtr += samplesToFeed;
    }
    this.rubberBand.process(this.inputHeapPtr, samplesToFeed, false);
  }

  private ensureHeapSize(frames: number) {
    if (frames > this.heapSizeFrames) {
      if (this.inputHeapPtr) this.rubberBand.module._free(this.inputHeapPtr);
      if (this.outputHeapPtr) this.rubberBand.module._free(this.outputHeapPtr);

      this.inputHeapPtr = this.rubberBand.module._malloc(frames * 4);
      this.outputHeapPtr = this.rubberBand.module._malloc(frames * 4);
      this.heapSizeFrames = frames;
    }
  }
}

registerProcessor('RubberBandProcessor', RubberBandProcessor);
